CREATE TABLE user_secondary_role (
    user_id bigint NOT NULL REFERENCES app_user(id),
    role varchar(20) NOT NULL REFERENCES role(name) CHECK (role = 'TEACHER'),
    PRIMARY KEY (user_id, role)
);

CREATE TABLE calendar_annotation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app_user(id),
    on_date date NOT NULL,
    title varchar(180) NOT NULL CHECK (length(trim(title)) > 0),
    content varchar(10000) NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX calendar_annotation_user_date ON calendar_annotation(user_id, on_date);

CREATE TABLE institutional_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id bigint NOT NULL REFERENCES app_user(id),
    on_date date NOT NULL,
    title varchar(180) NOT NULL CHECK (length(trim(title)) > 0),
    content varchar(10000) NOT NULL DEFAULT ''
);
CREATE INDEX institutional_event_date ON institutional_event(on_date);
CREATE INDEX institutional_event_author ON institutional_event(author_id);

CREATE TABLE schedule_break (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id bigint NOT NULL REFERENCES app_user(id),
    weekday integer NOT NULL CHECK (weekday BETWEEN 1 AND 7),
    starts_at time NOT NULL,
    ends_at time NOT NULL CHECK (ends_at > starts_at),
    title varchar(100) NOT NULL CHECK (length(trim(title)) > 0)
);
CREATE INDEX schedule_break_teacher_day ON schedule_break(teacher_id, weekday);

CREATE TABLE direct_conversation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind varchar(20) NOT NULL CHECK (kind IN ('STAFF', 'ADMIN_DIRECT')),
    first_user_id bigint NOT NULL REFERENCES app_user(id),
    second_user_id bigint NOT NULL REFERENCES app_user(id),
    created_by bigint NOT NULL REFERENCES app_user(id),
    student_read_only boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (first_user_id < second_user_id),
    CHECK (created_by IN (first_user_id, second_user_id)),
    CHECK (kind = 'ADMIN_DIRECT' OR NOT student_read_only),
    UNIQUE (kind, first_user_id, second_user_id)
);
CREATE INDEX direct_conversation_second ON direct_conversation(second_user_id);
CREATE INDEX direct_conversation_creator ON direct_conversation(created_by);
CREATE TABLE direct_message (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint NOT NULL REFERENCES direct_conversation(id),
    sender_id bigint NOT NULL REFERENCES app_user(id),
    body varchar(3000) NOT NULL CHECK (length(trim(body)) > 0),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX direct_message_conversation ON direct_message(conversation_id, id);
CREATE INDEX direct_message_sender ON direct_message(sender_id);
